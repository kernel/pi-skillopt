// Central types for pi-skillopt.
//
// The "rollout environment spec" (RolloutEnv) is the heart of how a skill gets
// scored: it tells Harbor which sandbox to run in, which agent + model drives
// the task, and what to pre-load on the container before the agent starts.

export type Backend = "docker" | "daytona" | "e2b" | "runloop" | "modal" | "local";

/** The agent harness that executes each task inside the rollout container. */
export type AgentKind = "claude-code" | "codex" | "pi" | "opencode" | (string & {});

/** How a single Harbor rollout container is provisioned and driven. */
export interface RolloutEnv {
  /** Container/sandbox provider Harbor runs tasks in. */
  backend: Backend;
  /** The agent harness that runs each task with the candidate skill mounted. */
  agent: AgentKind;
  /** Provider model id, e.g. "anthropic/claude-opus-4-7", "openai/gpt-5.5". */
  model: string;
  /** Base image, or a path to a Dockerfile, the container starts from. */
  image?: string;
  /** Everything to pre-load before the agent runs a task. */
  setup?: RolloutSetup;
  /** Backend-specific knobs (region, cpu/mem, per-task timeout) passed through to Harbor. */
  extra?: Record<string, unknown>;
}

export interface RolloutSetup {
  /** Other SKILL.md files the agent should also have available (paths, repo refs, or registry ids). */
  skills?: string[];
  /** npm packages / CLIs to install globally. */
  npm?: string[];
  /** apt packages. */
  apt?: string[];
  /** pip packages. */
  pip?: string[];
  /**
   * Names of env vars / secrets to pass through. Values are supplied by the
   * backend's secret store at run time and are NEVER written to any session file.
   */
  env?: string[];
  /** Arbitrary setup commands, run after the package installs. */
  commands?: string[];
}

export type GateMetric = "hard" | "soft" | "mixed";
export type LrSchedule = "constant" | "linear" | "cosine";

/** Persisted as JSON to skillopt.config.json — the full description of an optimization run. */
export interface SkillOptConfig {
  /** Human-readable session name. */
  name: string;
  /** Path to the SKILL.md being optimized. This is the ONLY file the loop edits. */
  skillUnderTest: string;
  /** Path / ref to the Harbor task pack (generated by skillopt-taskpack). */
  taskPack: string;
  rollout: RolloutEnv;
  splits: Splits;
  /** Max edits applied per step — the textual learning rate. */
  editBudget: number;
  minEditBudget?: number;
  lrSchedule?: LrSchedule;
  gateMetric?: GateMetric;
  /** Weight on soft when gateMetric === "mixed". */
  mixedWeight?: number;
  /** Re-roll the selection split this many times and average (noise control). Default 1. */
  selectionSamples?: number;
  maxSteps?: number | null;
  workingDir?: string;
}

export interface Splits {
  train: string[];
  selection: string[];
  test: string[];
}

export interface PerTaskResult {
  taskId: string;
  /** 1 = passed all required verifiers, 0 = failed at least one. */
  hard: 0 | 1;
  /** Mean of the task's verifier rewards in [0,1]. */
  soft: number;
  /** Per-verifier breakdown, e.g. { outcome: 1, teardown: 0, adherence: 0.5 }. */
  rewards: Record<string, number>;
  /** Path to the captured ATIF trajectory for this run (used as the reflection "gradient"). */
  trajectory?: string;
}

export interface RolloutResult {
  split: "train" | "selection" | "test";
  /** Mean hard score across tasks in the split, in [0,1]. */
  hard: number;
  /** Mean soft score across tasks in the split, in [0,1]. */
  soft: number;
  perTask: PerTaskResult[];
  /** A sampled subset of failing trajectories, surfaced to the agent as the gradient. */
  failing: PerTaskResult[];
}

export type GateAction = "accept_new_best" | "accept" | "reject";

/** One "step" line in skillopt.jsonl. */
export interface StepEntry {
  type: "step";
  step: number;
  segment: number;
  timestamp: number;
  /** Short description of the edit(s) the agent applied this step. */
  edit: string;
  /** Candidate selection-split scores. */
  sel_hard: number;
  sel_soft: number;
  gate_metric: GateMetric;
  action: GateAction;
  /** Metric-space selection score of current / best after this step. */
  current_score: number;
  best_score: number;
  /** Effective edit budget (LR) at this step. */
  edit_budget: number;
  /** Best-improvement vs selection-noise floor; null until enough data. */
  confidence: number | null;
  /** Snapshot filename for the skill version accepted this step, if any. */
  skill_version?: string;
}

/** The header line written to skillopt.jsonl on init_optimization. */
export interface ConfigHeaderEntry {
  type: "config";
  timestamp: number;
  name: string;
  skill_under_test: string;
  task_pack: string;
  gate_metric: GateMetric;
  splits: { train: number; selection: number; test: number };
}

export type JsonlEntry = StepEntry | ConfigHeaderEntry;
